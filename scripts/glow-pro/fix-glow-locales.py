def load_locale(path: Path):
    raw = path.read_text(encoding="utf-8-sig")
    match = re.match(r"^(\s*/\*[\s\S]*?\*/\s*)([\s\S]*)$", raw)
    header = match.group(1) if match else ""
    body = match.group(2) if match else raw
    return header, json.loads(body)


def save_locale(path: Path, header: str, data):
    path.write_text(header + json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


